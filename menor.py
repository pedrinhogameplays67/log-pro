# Passo 1 -> Ter 2 números
numero1 = int(input('Digite um número: '))
numero2 = int(input('Digite outro número: '))
numero3 = int(input('Digite mais outro número: '))
primeiraconta_mais = (numero1 + numero2)
segundaconta_mais = (primeiraconta_mais + numero3)
primeiraconta_menos = (numero1 - numero2)
segundaconta_menos = (primeiraconta_menos - numero3)
primeiraconta_vezes = (numero1 * numero2)
segundaconta_vezes = (primeiraconta_vezes * numero3)
primeiraconta_dividir = (numero1 / numero3)
segundaconta_dividir = (primeiraconta_dividir / numero3)
escolha_1_sinal = (input('Escolha o primeiro sinal da operação: '))
escolha_2_sinal = (input('Escolha o outro sinal da operação: '))




if escolha_1_sinal == '+':
    print(primeiraconta_mais)
elif escolha_1_sinal == '-':
    print(primeiraconta_menos)
elif escolha_1_sinal == '*':
    print(primeiraconta_vezes)
elif escolha_1_sinal == '/':
    print(primeiraconta_dividir)


if escolha_2_sinal == '+':
    print(segundaconta_mais)
elif escolha_2_sinal == '-':
    print(segundaconta_menos)
elif escolha_2_sinal == '*':
    print(segundaconta_vezes)
elif escolha_2_sinal == '/':
    print(segundaconta_dividir)


