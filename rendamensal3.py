renda_mensal = float(input('Digite sua renda mensal: '))
score  = 0.0
possui_restricao = False


if   renda_mensal >= 4000.00: 
    0 < score < 1000
    print('Aprovado')
else:
    possui_restricao
    print ('Reprovado')

if renda_mensal >= 2500.00 or renda_mensal >= 6000.00:
    score >= 500
    possui_restricao

    print('Recusado')